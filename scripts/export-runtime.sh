#!/usr/bin/env bash

export_runtime_init() {
  PK3S_EXPORT_METADATA_COMMAND=""
  PK3S_EXPORT_METADATA_SUBJECT_KIND=""
  PK3S_EXPORT_METADATA_SUBJECT_REF=""
  PK3S_EXPORT_METADATA_ARTIFACT_NAME=""
  PK3S_EXPORT_METADATA_PROFILE_SOURCE=""
  PK3S_EXPORT_ENV_KEYS=()
  unset PK3S_EXPORT_ENV_VALUES
  declare -gA PK3S_EXPORT_ENV_VALUES=()
}

export_runtime_shell_escape() {
  printf "%s" "$1" | sed "s/'/'\\\\''/g"
}

export_runtime_json_escape() {
  printf '%s' "$1" | sed \
    -e 's/\\/\\\\/g' \
    -e 's/"/\\"/g' \
    -e ':a;N;$!ba;s/\n/\\n/g' \
    -e 's/\r/\\r/g' \
    -e 's/\t/\\t/g'
}

export_runtime_add_env() {
  local key="$1"
  local value="$2"
  if [[ -z "${PK3S_EXPORT_ENV_VALUES[$key]+x}" ]]; then
    PK3S_EXPORT_ENV_KEYS+=("$key")
  fi
  PK3S_EXPORT_ENV_VALUES["$key"]="$value"
}

export_runtime_set_metadata() {
  local key="$1"
  local value="$2"
  case "$key" in
    command)
      PK3S_EXPORT_METADATA_COMMAND="$value"
      ;;
    subject_kind)
      PK3S_EXPORT_METADATA_SUBJECT_KIND="$value"
      ;;
    subject_ref)
      PK3S_EXPORT_METADATA_SUBJECT_REF="$value"
      ;;
    artifact_name)
      PK3S_EXPORT_METADATA_ARTIFACT_NAME="$value"
      ;;
    profile_source)
      PK3S_EXPORT_METADATA_PROFILE_SOURCE="$value"
      ;;
    *)
      printf 'Unsupported export metadata key: %s\n' "$key" >&2
      return 1
      ;;
  esac
}

export_runtime_write_install_config() {
  local target_path="$1"
  local key escaped_value
  {
    printf '# Generated by productive-k3s-infra export runtime\n'
    for key in "${PK3S_EXPORT_ENV_KEYS[@]}"; do
      escaped_value="$(export_runtime_shell_escape "${PK3S_EXPORT_ENV_VALUES[$key]}")"
      printf "export %s='%s'\n" "$key" "$escaped_value"
    done
  } > "${target_path}"
}

export_runtime_write_manifest() {
  local target_path="$1"
  {
    printf '{\n'
    printf '  "schema_version": "1",\n'
    printf '  "command": "%s",\n' "$(export_runtime_json_escape "${PK3S_EXPORT_METADATA_COMMAND}")"
    printf '  "subject": {\n'
    printf '    "kind": "%s",\n' "$(export_runtime_json_escape "${PK3S_EXPORT_METADATA_SUBJECT_KIND}")"
    printf '    "ref": "%s",\n' "$(export_runtime_json_escape "${PK3S_EXPORT_METADATA_SUBJECT_REF}")"
    printf '  },\n'
    printf '  "artifact": {\n'
    printf '    "name": "%s",\n' "$(export_runtime_json_escape "${PK3S_EXPORT_METADATA_ARTIFACT_NAME}")"
    printf '    "profile_source": "%s"\n' "$(export_runtime_json_escape "${PK3S_EXPORT_METADATA_PROFILE_SOURCE}")"
    printf '  }\n'
    printf '}\n'
  } > "${target_path}"
}

export_runtime_infra_runtime_paths() {
  cat <<'EOF'
LICENSE
README.md
productive-k3s-infra.sh
scripts/productive-k3s-infra.sh
scripts/release-config.sh
scripts/send-telemetry-event.sh
scripts/export-runtime.sh
EOF
}

export_runtime_copy_infra_runtime() {
  local repo_root="$1"
  local bundle_root="$2"
  local relative_path

  while IFS= read -r relative_path; do
    [[ -n "${relative_path}" ]] || continue
    mkdir -p "${bundle_root}/$(dirname "${relative_path}")"
    cp -R "${repo_root}/${relative_path}" "${bundle_root}/${relative_path}"
  done < <(export_runtime_infra_runtime_paths)

  chmod +x "${bundle_root}/productive-k3s-infra.sh" "${bundle_root}/scripts/productive-k3s-infra.sh"
}

export_runtime_write_profile_install_script() {
  local target_path="$1"
  local artifact_name="$2"
  local has_override_env="${3:-false}"

  {
    printf '#!/usr/bin/env bash\n'
    printf 'set -euo pipefail\n\n'
    printf 'SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"\n'
    printf 'if [[ -f "${SCRIPT_DIR}/install-config.env" ]]; then\n'
    printf '  # shellcheck disable=SC1091\n'
    printf '  source "${SCRIPT_DIR}/install-config.env"\n'
    printf 'fi\n\n'
    printf 'ARGS=(profile install --tgz "${SCRIPT_DIR}/%s")\n' "${artifact_name}"
    if [[ "${has_override_env}" == "true" ]]; then
      printf 'ARGS+=(--env-file "${SCRIPT_DIR}/override.env")\n'
    fi
    printf 'exec "${SCRIPT_DIR}/productive-k3s-infra.sh" "${ARGS[@]}" "$@"\n'
  } > "${target_path}"

  chmod +x "${target_path}"
}

export_runtime_write_readme() {
  local target_path="$1"
  local subject_ref="$2"
  local artifact_name="$3"
  cat > "${target_path}" <<EOF
# Productive K3S Exported Profile Bundle

This bundle replays the exported profile installation for \`${subject_ref}\`.

## Contents

- \`install.sh\` replays the exported installation using the bundled Infra runtime.
- \`${artifact_name}\` is the packaged profile artifact consumed by the installer.
- \`install-config.env\` freezes exported environment defaults for this bundle.
- \`manifest.json\` records the exported command metadata.

## Usage

\`\`\`bash
./install.sh
\`\`\`

This bundle is self-contained with respect to Productive K3S tooling, but it may still require host prerequisites and network access at install time.
EOF
}
